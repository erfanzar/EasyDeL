"""Immutable online-RL trajectory records and mask-preserving collation."""

from __future__ import annotations

import types
import typing as tp
from dataclasses import dataclass, field

import numpy as np

SpanKind = tp.Literal["prompt", "action", "observation", "compaction", "resume"]
SegmentKind = tp.Literal["execution", "compaction"]
PaddingSide = tp.Literal["left", "right"]
TruncationSide = tp.Literal["left", "right"]

_SPAN_KINDS = frozenset({"prompt", "action", "observation", "compaction", "resume"})
_SEGMENT_KINDS = frozenset({"execution", "compaction"})


def _readonly_array(value: np.ndarray | tp.Sequence[tp.Any], *, dtype: np.dtype) -> np.ndarray:
    """Copy an array and make its storage read-only."""

    result = np.array(value, dtype=dtype, copy=True)
    result.flags.writeable = False
    return result


@dataclass(frozen=True, slots=True)
class TrajectorySpan:
    """One semantically homogeneous token span in a rollout.

    Args:
        start: Inclusive token offset.
        stop: Exclusive token offset.
        kind: Role of the tokens in the span.
        segment_id: Optional owning trajectory segment.
    """

    start: int
    stop: int
    kind: SpanKind
    segment_id: int | None = None

    def __post_init__(self) -> None:
        """Validate half-open bounds and role metadata."""

        if self.start < 0 or self.stop <= self.start:
            raise ValueError(f"span bounds must satisfy 0 <= start < stop; got [{self.start}, {self.stop})")
        if self.kind not in _SPAN_KINDS:
            raise ValueError(f"unsupported span kind {self.kind!r}")
        if self.segment_id is not None and self.segment_id < 0:
            raise ValueError(f"segment_id must be non-negative, got {self.segment_id}")

    @property
    def length(self) -> int:
        """Number of tokens in the span."""

        return self.stop - self.start


@dataclass(frozen=True, slots=True)
class TrajectorySegment:
    """One execution or policy-generated compaction segment.

    Args:
        segment_id: Episode-local, non-negative segment identifier.
        start: Inclusive token offset.
        stop: Exclusive token offset.
        kind: ``"execution"`` or ``"compaction"``.
        is_terminal: Whether this segment ends the episode.
    """

    segment_id: int
    start: int
    stop: int
    kind: SegmentKind = "execution"
    is_terminal: bool = False

    def __post_init__(self) -> None:
        """Validate segment identity, bounds, and kind."""

        if self.segment_id < 0:
            raise ValueError(f"segment_id must be non-negative, got {self.segment_id}")
        if self.start < 0 or self.stop <= self.start:
            raise ValueError(f"segment bounds must satisfy 0 <= start < stop; got [{self.start}, {self.stop})")
        if self.kind not in _SEGMENT_KINDS:
            raise ValueError(f"unsupported segment kind {self.kind!r}")

    @property
    def length(self) -> int:
        """Number of tokens in the segment."""

        return self.stop - self.start


@dataclass(frozen=True, slots=True, eq=False)
class OnlineRLTrajectory:
    """Immutable token-level record for a single online-RL episode.

    Attention and action masks are deliberately separate. Environment
    observations and reconstructed context remain visible to the model through
    ``attention_mask`` while ``action_mask`` limits policy gradients to tokens
    generated by the trainable policy.

    The schema can record several semantic segments for storage or analysis,
    but the standard online actor/critic scorer accepts only one optimized
    segment per row. Compacted segments have different causal contexts and
    must be collated as separate full-context rows sharing ``trajectory_id``.

    Args:
        input_ids: One-dimensional token IDs.
        attention_mask: Valid-context mask.
        action_mask: Policy-generated-token mask.
        rewards: Per-token reward values.
        behavior_logps: Optional per-token log-probabilities recorded from the
            policy snapshot that generated the rollout. Values must be finite;
            non-action values are ignored by collation.
        transition_mask: Optional continuation mask on action positions. When
            omitted, consecutive actions transition only within the same
            declared segment. Trajectories without declared segments use one
            implicit segment.
        spans: Ordered, non-overlapping semantic spans.
        segments: Ordered, non-overlapping execution/compaction segments.
        trajectory_id: Optional non-negative learner grouping ID. When omitted,
            collation assigns an independent ID to the row.
        policy_version: Version of the policy snapshot that generated the
            trajectory.
        metadata: Shallow immutable diagnostic metadata.
    """

    input_ids: np.ndarray
    attention_mask: np.ndarray
    action_mask: np.ndarray
    rewards: np.ndarray
    behavior_logps: np.ndarray | None = None
    transition_mask: np.ndarray | None = None
    spans: tuple[TrajectorySpan, ...] = ()
    segments: tuple[TrajectorySegment, ...] = ()
    trajectory_id: int | None = None
    policy_version: int = 0
    metadata: tp.Mapping[str, tp.Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        """Normalize storage and enforce trajectory invariants."""

        input_ids = _readonly_array(self.input_ids, dtype=np.dtype(np.int64))
        attention_mask = _readonly_array(self.attention_mask, dtype=np.dtype(np.bool_))
        action_mask = _readonly_array(self.action_mask, dtype=np.dtype(np.bool_))
        rewards = _readonly_array(self.rewards, dtype=np.dtype(np.float32))
        behavior_logps = (
            None if self.behavior_logps is None else _readonly_array(self.behavior_logps, dtype=np.dtype(np.float32))
        )

        arrays = {
            "input_ids": input_ids,
            "attention_mask": attention_mask,
            "action_mask": action_mask,
            "rewards": rewards,
        }
        if behavior_logps is not None:
            arrays["behavior_logps"] = behavior_logps
        for name, value in arrays.items():
            if value.ndim != 1:
                raise ValueError(f"{name} must be one-dimensional, got shape {value.shape}")
        length = input_ids.shape[0]
        if any(value.shape[0] != length for value in arrays.values()):
            shapes = {name: value.shape for name, value in arrays.items()}
            raise ValueError(f"all token arrays must have identical lengths, got {shapes}")
        if length == 0:
            raise ValueError("a trajectory must contain at least one token")
        if np.any(action_mask & ~attention_mask):
            raise ValueError("action_mask cannot select tokens outside attention_mask")
        if not np.all(np.isfinite(rewards)):
            raise ValueError("rewards must contain only finite values")
        if behavior_logps is not None and not np.all(np.isfinite(behavior_logps)):
            raise ValueError("behavior_logps must contain only finite values")

        spans = tuple(self.spans)
        segments = tuple(self.segments)
        self._validate_regions(spans, length, "span")
        self._validate_regions(segments, length, "segment")
        segment_ids = [segment.segment_id for segment in segments]
        if len(set(segment_ids)) != len(segment_ids):
            raise ValueError("segment IDs must be unique within a trajectory")
        known_segment_ids = set(segment_ids)
        for span in spans:
            if span.segment_id is not None and span.segment_id not in known_segment_ids:
                raise ValueError(f"span references unknown segment_id {span.segment_id}")

        if self.transition_mask is None:
            transition_mask = np.zeros(length, dtype=np.bool_)
            action_positions = np.flatnonzero(action_mask)
            if action_positions.size > 1:
                if segments:
                    token_segment_ids = np.full(length, -1, dtype=np.int32)
                    for segment in segments:
                        token_segment_ids[segment.start : segment.stop] = segment.segment_id
                    current_segments = token_segment_ids[action_positions[:-1]]
                    next_segments = token_segment_ids[action_positions[1:]]
                    transition_mask[action_positions[:-1]] = (current_segments >= 0) & (
                        current_segments == next_segments
                    )
                else:
                    transition_mask[action_positions[:-1]] = True
            transition_mask.flags.writeable = False
        else:
            transition_mask = _readonly_array(self.transition_mask, dtype=np.dtype(np.bool_))
            if transition_mask.ndim != 1 or transition_mask.shape[0] != length:
                raise ValueError(
                    "transition_mask must be one-dimensional and match input_ids; "
                    f"got {transition_mask.shape} and {input_ids.shape}"
                )
            if np.any(transition_mask & ~action_mask):
                raise ValueError("transition_mask can only select action tokens")

        if self.trajectory_id is not None and self.trajectory_id < 0:
            raise ValueError(f"trajectory_id must be non-negative when set, got {self.trajectory_id}")
        if self.policy_version < 0:
            raise ValueError(f"policy_version must be non-negative, got {self.policy_version}")

        object.__setattr__(self, "input_ids", input_ids)
        object.__setattr__(self, "attention_mask", attention_mask)
        object.__setattr__(self, "action_mask", action_mask)
        object.__setattr__(self, "rewards", rewards)
        object.__setattr__(self, "behavior_logps", behavior_logps)
        object.__setattr__(self, "transition_mask", transition_mask)
        object.__setattr__(self, "spans", spans)
        object.__setattr__(self, "segments", segments)
        object.__setattr__(self, "metadata", types.MappingProxyType(dict(self.metadata)))

    @staticmethod
    def _validate_regions(
        regions: tuple[TrajectorySpan, ...] | tuple[TrajectorySegment, ...],
        trajectory_length: int,
        name: str,
    ) -> None:
        """Validate ordered, non-overlapping in-bounds regions."""

        previous_stop = 0
        for region in regions:
            if region.stop > trajectory_length:
                raise ValueError(f"{name} [{region.start}, {region.stop}) exceeds trajectory length {trajectory_length}")
            if region.start < previous_stop:
                raise ValueError(f"{name}s must be ordered and non-overlapping")
            previous_stop = region.stop

    @property
    def length(self) -> int:
        """Number of stored tokens."""

        return int(self.input_ids.shape[0])

    @property
    def optimized_token_count(self) -> int:
        """Number of policy-generated tokens."""

        return int(np.count_nonzero(self.action_mask))

    def segment_ids(self) -> np.ndarray:
        """Materialize token-aligned segment IDs.

        Tokens outside declared segments receive ``-1``. If no segments were
        declared, all valid tokens belong to an implicit segment zero.

        Returns:
            A read-only int32 array.
        """

        ids = np.full(self.length, -1, dtype=np.int32)
        if self.segments:
            for segment in self.segments:
                ids[segment.start : segment.stop] = segment.segment_id
        else:
            ids[self.attention_mask] = 0
        ids.flags.writeable = False
        return ids


def _truncate_trajectory(
    trajectory: OnlineRLTrajectory,
    *,
    max_length: int,
    truncation_side: TruncationSide,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Slice one trajectory and sever transitions whose successor was removed."""

    length = trajectory.length
    if length <= max_length:
        start, stop = 0, length
    elif truncation_side == "right":
        start, stop = 0, max_length
    else:
        start, stop = length - max_length, length

    input_ids = np.array(trajectory.input_ids[start:stop], copy=True)
    attention_mask = np.array(trajectory.attention_mask[start:stop], copy=True)
    action_mask = np.array(trajectory.action_mask[start:stop], copy=True)
    rewards = np.array(trajectory.rewards[start:stop], copy=True)
    transition_mask = np.array(trajectory.transition_mask[start:stop], copy=True)
    segment_ids = np.array(trajectory.segment_ids()[start:stop], copy=True)
    behavior_logps = np.full(stop - start, np.nan, dtype=np.float32)
    if trajectory.behavior_logps is not None:
        sliced_behavior_logps = np.asarray(trajectory.behavior_logps[start:stop], dtype=np.float32)
        behavior_logps[action_mask] = sliced_behavior_logps[action_mask]

    retained_actions = np.flatnonzero(action_mask)
    original_actions = np.flatnonzero(trajectory.action_mask)
    if retained_actions.size:
        last_local_action = int(retained_actions[-1])
        last_global_action = start + last_local_action
        successor_was_truncated = bool(np.any(original_actions > last_global_action)) and not bool(
            np.any(retained_actions > last_local_action)
        )
        if successor_was_truncated:
            transition_mask[last_local_action] = False

    return input_ids, attention_mask, action_mask, rewards, behavior_logps, transition_mask, segment_ids


def collate_trajectories(
    trajectories: tp.Sequence[OnlineRLTrajectory],
    *,
    max_length: int,
    pad_token_id: int,
    padding_side: PaddingSide = "right",
    truncation_side: TruncationSide = "right",
) -> dict[str, np.ndarray]:
    """Pad trajectories and expose token- and target-aligned training arrays.

    Truncation never leaves an action connected to a successor action that was
    removed from the batch. Target masks are shifted onto
    ``input_ids[:, 1:]`` and require valid attention at both the predictor and
    target positions, which is safe for left as well as right padding.

    Args:
        trajectories: Non-empty trajectory sequence.
        max_length: Positive padded sequence length. At least two positions are
            required for causal next-token training.
        pad_token_id: Token ID used for padding.
        padding_side: Side on which shorter trajectories are padded.
        truncation_side: Side removed from overlength trajectories.

    Returns:
        A dictionary containing full token arrays plus ``target_*`` arrays
        aligned with ``input_ids[:, 1:]``. ``behavior_logps`` and
        ``target_behavior_logps`` use ``NaN`` wherever a log-probability is
        missing or the token is not an optimized action.

    Raises:
        ValueError: If arguments are invalid or no trajectories are supplied.
    """

    if not trajectories:
        raise ValueError("trajectories must be non-empty")
    if max_length < 2:
        raise ValueError(f"max_length must be at least 2, got {max_length}")
    if padding_side not in {"left", "right"}:
        raise ValueError(f"padding_side must be 'left' or 'right', got {padding_side!r}")
    if truncation_side not in {"left", "right"}:
        raise ValueError(f"truncation_side must be 'left' or 'right', got {truncation_side!r}")

    batch_size = len(trajectories)
    input_ids = np.full((batch_size, max_length), pad_token_id, dtype=np.int64)
    attention_mask = np.zeros((batch_size, max_length), dtype=np.bool_)
    action_mask = np.zeros((batch_size, max_length), dtype=np.bool_)
    rewards = np.zeros((batch_size, max_length), dtype=np.float32)
    behavior_logps = np.full((batch_size, max_length), np.nan, dtype=np.float32)
    transition_mask = np.zeros((batch_size, max_length), dtype=np.bool_)
    segment_ids = np.full((batch_size, max_length), -1, dtype=np.int32)
    policy_versions = np.empty((batch_size,), dtype=np.int64)
    trajectory_ids = np.empty((batch_size,), dtype=np.int64)
    lengths = np.empty((batch_size,), dtype=np.int32)
    reserved_trajectory_ids = {
        int(trajectory.trajectory_id) for trajectory in trajectories if trajectory.trajectory_id is not None
    }
    next_automatic_trajectory_id = 0

    for row, trajectory in enumerate(trajectories):
        (
            row_ids,
            row_attention,
            row_actions,
            row_rewards,
            row_behavior_logps,
            row_transitions,
            row_segments,
        ) = _truncate_trajectory(
            trajectory,
            max_length=max_length,
            truncation_side=truncation_side,
        )
        row_length = row_ids.shape[0]
        destination = slice(max_length - row_length, max_length) if padding_side == "left" else slice(0, row_length)
        input_ids[row, destination] = row_ids
        attention_mask[row, destination] = row_attention
        action_mask[row, destination] = row_actions
        rewards[row, destination] = row_rewards
        behavior_logps[row, destination] = row_behavior_logps
        transition_mask[row, destination] = row_transitions
        segment_ids[row, destination] = row_segments
        if trajectory.trajectory_id is None:
            while next_automatic_trajectory_id in reserved_trajectory_ids:
                next_automatic_trajectory_id += 1
            trajectory_ids[row] = next_automatic_trajectory_id
            reserved_trajectory_ids.add(next_automatic_trajectory_id)
            next_automatic_trajectory_id += 1
        else:
            trajectory_ids[row] = trajectory.trajectory_id
        policy_versions[row] = trajectory.policy_version
        lengths[row] = row_length

    valid_target_pair = attention_mask[:, :-1] & attention_mask[:, 1:]
    target_action_mask = action_mask[:, 1:] & valid_target_pair
    target_transition_mask = transition_mask[:, 1:] & target_action_mask

    return {
        "input_ids": input_ids,
        "attention_mask": attention_mask,
        "action_mask": action_mask,
        "rewards": rewards,
        "behavior_logps": behavior_logps,
        "transition_mask": transition_mask,
        "segment_ids": segment_ids,
        "trajectory_ids": trajectory_ids,
        "policy_versions": policy_versions,
        "lengths": lengths,
        "target_ids": input_ids[:, 1:],
        "target_attention_mask": valid_target_pair,
        "target_action_mask": target_action_mask,
        "target_rewards": rewards[:, 1:],
        "target_behavior_logps": behavior_logps[:, 1:],
        "target_transition_mask": target_transition_mask,
        "target_segment_ids": segment_ids[:, 1:],
    }


@dataclass(frozen=True, slots=True)
class OnlineRLTrajectoryCollator:
    """Callable configuration wrapper around :func:`collate_trajectories`."""

    max_length: int
    pad_token_id: int
    padding_side: PaddingSide = "right"
    truncation_side: TruncationSide = "right"

    def __post_init__(self) -> None:
        """Validate collation arguments eagerly."""

        if self.max_length < 2:
            raise ValueError(f"max_length must be at least 2, got {self.max_length}")
        if self.padding_side not in {"left", "right"}:
            raise ValueError(f"padding_side must be 'left' or 'right', got {self.padding_side!r}")
        if self.truncation_side not in {"left", "right"}:
            raise ValueError(f"truncation_side must be 'left' or 'right', got {self.truncation_side!r}")

    def __call__(self, trajectories: tp.Sequence[OnlineRLTrajectory]) -> dict[str, np.ndarray]:
        """Collate a trajectory sequence with the stored configuration."""

        return collate_trajectories(
            trajectories,
            max_length=self.max_length,
            pad_token_id=self.pad_token_id,
            padding_side=self.padding_side,
            truncation_side=self.truncation_side,
        )


