"""Step3 tool parser module.

This module provides the Step3ToolParser class for parsing XML-like tool calls
generated by Step3 models.

Example format parsed:
    <｜tool_calls_begin｜>
    <｜tool_call_begin｜>
    function<｜tool_sep｜>
    <steptml:invoke name="func">
    <steptml:parameter name="param">value</steptml:parameter>
    </steptml:invoke>
    <｜tool_call_end｜>
    <｜tool_calls_end｜>

Note:
    Uses fullwidth vertical line characters (｜) as delimiters.
"""

from __future__ import annotations

import json
import re
from collections.abc import Sequence
from typing import Any
from uuid import uuid4

from eformer.loggings import get_logger
from transformers import AutoTokenizer as AnyTokenizer

from ...openai_api_modules import (
    ChatCompletionRequest,
    DeltaFunctionCall,
    DeltaMessage,
    DeltaToolCall,
    ExtractedToolCallInformation,
    FunctionCall,
    ToolCall,
)
from ..abstract_tool import ToolParser, ToolParserManager
from ._schema_params import convert_param_value, lookup_tool_properties

logger = get_logger(__name__)


def _trailing_prefix_len(text: str, marker: str) -> int:
    """Return length of the longest proper prefix of *marker* matching the end of *text*."""
    max_len = min(len(text), len(marker) - 1)
    for size in range(max_len, 0, -1):
        if text.endswith(marker[:size]):
            return size
    return 0


@ToolParserManager.register_module(["step3"])  # pyright: ignore[reportUntypedClassDecorator]
class Step3ToolParser(ToolParser):
    """Tool parser for Step3 models with XML-like format.

    Supports multiple ``<｜tool_calls_begin｜>...<｜tool_calls_end｜>`` blocks,
    parameters containing ``<`` characters, structured ``object``/``array`` schema
    coercion, zero-argument calls, split delimiters, and single-chunk streaming.
    """

    TOOL_CALLS_BEGIN = "<\uff5ctool_calls_begin\uff5c>"
    TOOL_CALLS_END = "<\uff5ctool_calls_end\uff5c>"
    TOOL_CALL_BEGIN = "<\uff5ctool_call_begin\uff5c>"
    TOOL_CALL_END = "<\uff5ctool_call_end\uff5c>"
    TOOL_SEP = "<\uff5ctool_sep\uff5c>"
    SPECIAL_TOKENS = (TOOL_CALLS_BEGIN, TOOL_CALLS_END, TOOL_CALL_BEGIN, TOOL_CALL_END)

    def __init__(self, tokenizer: AnyTokenizer):
        """Initialize the Step3 tool parser."""
        super().__init__(tokenizer)
        self._reset_streaming_state()

    def get_streaming_buffer_marker_pairs(self) -> Sequence[tuple[str, str | None]]:
        """Scope protocol buffering strictly to outer ``TOOL_CALLS_BEGIN``/``TOOL_CALLS_END`` markers."""
        return ((self.TOOL_CALLS_BEGIN, self.TOOL_CALLS_END),)

    def is_buffering_protocol(
        self,
        *,
        current_text: str,
        delta_text: str,
    ) -> bool:
        """Return True while inside an active ``TOOL_CALLS_BEGIN`` block or trailing prefix."""
        if self._streaming_initialized:
            if self.tool_block_started or self._in_single_call:
                return True
            return self._has_trailing_marker_prefix(
                current_text[self.position :],
                (self.TOOL_CALLS_BEGIN,),
            )
        return super().is_buffering_protocol(current_text=current_text, delta_text=delta_text)

    def _reset_streaming_state(self) -> None:
        """Reset all streaming cursor and call tracking state."""
        self.position = 0
        self.tool_block_started = False
        self.tool_block_finished = False
        self.current_tool_id = -1
        self.current_tool_name_sent = False
        self.prev_tool_call_arr = []
        self.streamed_args_for_tool = []
        self._streaming_initialized = False
        self._accumulated_text = ""
        self._in_single_call = False
        self._next_tool_index = 0

    def flush_streaming_content(self) -> str:
        """Release withheld opening-tag prefix when the stream ends outside a tool block."""
        if self.tool_block_started:
            self._accumulated_text = ""
            self.position = 0
            return ""
        pending = self._accumulated_text[self.position :]
        self._accumulated_text = ""
        self.position = 0
        return pending

    def adjust_request(self, request: ChatCompletionRequest) -> ChatCompletionRequest:
        """Adjust the request to ensure special tokens are not skipped."""
        if request.tools and request.tool_choice != "none":
            request.skip_special_tokens = False
        return request

    @staticmethod
    def _parse_steptml_invoke(action_text: str) -> tuple[str | None, dict[str, str] | None]:
        """Parse a steptml:invoke element to extract function name and parameters (allowing ``<`` in values)."""
        func_name_match = re.search(r'<steptml:invoke name="([^"]+)">', action_text)
        if not func_name_match:
            return None, None
        func_name = func_name_match.group(1)

        params: dict[str, str] = {}
        param_matches = re.findall(
            r'<steptml:parameter name="([^"]+)">(.*?)</steptml:parameter>',
            action_text,
            re.DOTALL,
        )
        for name, value in param_matches:
            params[name] = value.strip()
        return func_name, params

    def _cast_arguments(
        self,
        func_name: str,
        params: dict[str, Any],
        request: ChatCompletionRequest | None,
    ) -> dict[str, Any]:
        """Cast argument values to their schema-defined types (including ``object`` and ``array``)."""
        tools = request.tools if request else None
        properties = lookup_tool_properties(func_name, tools)
        if not properties:
            return params
        casted: dict[str, Any] = {}
        for key, value in params.items():
            if not isinstance(value, str) or key not in properties:
                casted[key] = value
                continue
            try:
                casted[key] = convert_param_value(value, key, properties, func_name)
            except (RecursionError, MemoryError):
                casted[key] = value
        return casted

    def extract_tool_calls_streaming(
        self,
        previous_text: str,
        current_text: str,
        delta_text: str,
        previous_token_ids: Sequence[int],
        current_token_ids: Sequence[int],
        delta_token_ids: Sequence[int],
        request: ChatCompletionRequest,
    ) -> DeltaMessage | None:
        """Extract tool calls incrementally from streaming model output."""
        del delta_text, previous_token_ids, current_token_ids, delta_token_ids
        if not previous_text:
            self._reset_streaming_state()
            self._streaming_initialized = True
        elif not self._streaming_initialized:
            self._reset_streaming_state()
            self.position = len(previous_text)
            self._streaming_initialized = True

        self._accumulated_text = current_text
        content_parts: list[str] = []
        tool_deltas: list[DeltaToolCall] = []

        while self.position < len(current_text):
            unprocessed_text = current_text[self.position :]

            if not self.tool_block_started:
                if unprocessed_text.startswith(self.TOOL_CALLS_BEGIN):
                    self.position += len(self.TOOL_CALLS_BEGIN)
                    self.tool_block_started = True
                    continue

                start_pos = unprocessed_text.find(self.TOOL_CALLS_BEGIN)
                if start_pos == -1:
                    hold = _trailing_prefix_len(unprocessed_text, self.TOOL_CALLS_BEGIN)
                    emit_len = len(unprocessed_text) - hold
                    if emit_len > 0:
                        content_parts.append(unprocessed_text[:emit_len])
                        self.position += emit_len
                    break

                if start_pos > 0:
                    content_parts.append(unprocessed_text[:start_pos])
                    self.position += start_pos
                self.position += len(self.TOOL_CALLS_BEGIN)
                self.tool_block_started = True
                continue

            # Inside <|tool_calls_begin|> ... <|tool_calls_end|>.
            if not self._in_single_call:
                offset = len(unprocessed_text) - len(unprocessed_text.lstrip())
                if offset:
                    self.position += offset
                    unprocessed_text = unprocessed_text[offset:]
                    if not unprocessed_text:
                        break

                if unprocessed_text.startswith(self.TOOL_CALLS_END):
                    self.position += len(self.TOOL_CALLS_END)
                    self.tool_block_started = False
                    self.current_tool_id = -1
                    continue

                if unprocessed_text.startswith(self.TOOL_CALL_BEGIN):
                    self.position += len(self.TOOL_CALL_BEGIN)
                    self._in_single_call = True
                    self.current_tool_name_sent = False
                    continue

                if self.TOOL_CALL_BEGIN.startswith(unprocessed_text) or self.TOOL_CALLS_END.startswith(
                    unprocessed_text
                ):
                    break

                # Skip unexpected text before next marker inside a tool block.
                next_begin = unprocessed_text.find(self.TOOL_CALL_BEGIN)
                next_end = unprocessed_text.find(self.TOOL_CALLS_END)
                candidates = [p for p in (next_begin, next_end) if p != -1]
                if candidates:
                    self.position += min(candidates)
                    continue
                break

            # Inside <|tool_call_begin|> ... <|tool_call_end|>, bounded by <|tool_calls_end|>.
            end_block_pos = unprocessed_text.find(self.TOOL_CALLS_END)
            search_limit = end_block_pos if end_block_pos != -1 else len(unprocessed_text)
            end_tool_pos = unprocessed_text.find(self.TOOL_CALL_END, 0, search_limit)
            closed_by_block = end_tool_pos == -1 and end_block_pos != -1
            if end_tool_pos != -1:
                tool_body = unprocessed_text[:end_tool_pos]
            elif closed_by_block:
                tool_body = unprocessed_text[:end_block_pos]
            else:
                tool_body = unprocessed_text

            if self.TOOL_SEP not in tool_body:
                if end_tool_pos != -1:
                    # Malformed call missing TOOL_SEP: discard and advance past TOOL_CALL_END.
                    self.position += end_tool_pos + len(self.TOOL_CALL_END)
                    self._in_single_call = False
                    continue
                if closed_by_block:
                    self.position += end_block_pos + len(self.TOOL_CALLS_END)
                    self._in_single_call = False
                    self.tool_block_started = False
                    self.current_tool_id = -1
                    continue
                break

            type_part, invoke_part = tool_body.split(self.TOOL_SEP, 1)
            if type_part.strip() != "function":
                if end_tool_pos != -1:
                    self.position += end_tool_pos + len(self.TOOL_CALL_END)
                    self._in_single_call = False
                    continue
                if closed_by_block:
                    self.position += end_block_pos + len(self.TOOL_CALLS_END)
                    self._in_single_call = False
                    self.tool_block_started = False
                    self.current_tool_id = -1
                    continue
                break

            function_name, arguments = self._parse_steptml_invoke(invoke_part)
            if not function_name:
                if end_tool_pos != -1:
                    self.position += end_tool_pos + len(self.TOOL_CALL_END)
                    self._in_single_call = False
                    continue
                if closed_by_block:
                    self.position += end_block_pos + len(self.TOOL_CALLS_END)
                    self._in_single_call = False
                    self.tool_block_started = False
                    self.current_tool_id = -1
                    continue
                break

            if not self.current_tool_name_sent:
                tool_idx = self._next_tool_index
                self._next_tool_index += 1
                self.current_tool_id = tool_idx
                self.current_tool_name_sent = True
                while len(self.prev_tool_call_arr) <= tool_idx:
                    self.prev_tool_call_arr.append({})
                while len(self.streamed_args_for_tool) <= tool_idx:
                    self.streamed_args_for_tool.append("")
                self.prev_tool_call_arr[tool_idx] = {
                    "name": function_name,
                    "parameters": arguments or {},
                    "finished": False,
                }
                tool_deltas.append(
                    DeltaToolCall(
                        index=tool_idx,
                        type="function",
                        id=f"chatcmpl-tool-{uuid4()}",
                        function=DeltaFunctionCall(name=function_name),
                    )
                )

            tool_idx = self.current_tool_id
            self.prev_tool_call_arr[tool_idx].update({"name": function_name, "parameters": arguments or {}})

            if end_tool_pos != -1 or closed_by_block:
                if end_tool_pos != -1:
                    self.position += end_tool_pos + len(self.TOOL_CALL_END)
                else:
                    self.position += end_block_pos + len(self.TOOL_CALLS_END)
                    self.tool_block_started = False
                    self.current_tool_id = -1
                self._in_single_call = False
                self.prev_tool_call_arr[tool_idx]["finished"] = True

                final_args = self._cast_arguments(function_name, dict(arguments or {}), request)
                try:
                    final_args_json = json.dumps(final_args, ensure_ascii=False)
                except (TypeError, ValueError, RecursionError):
                    final_args_json = json.dumps(dict(arguments or {}), ensure_ascii=False)
                self.streamed_args_for_tool[tool_idx] = final_args_json
                if tool_deltas and tool_deltas[-1].index == tool_idx and tool_deltas[-1].function is not None:
                    tool_deltas[-1].function.arguments = final_args_json
                else:
                    tool_deltas.append(
                        DeltaToolCall(
                            index=tool_idx,
                            function=DeltaFunctionCall(arguments=final_args_json),
                        )
                    )
                continue

            break

        content = "".join(content_parts)
        if content or tool_deltas:
            return DeltaMessage(content=content or None, tool_calls=tool_deltas or None)
        return None

    def extract_tool_calls(
        self,
        model_output: str,
        request: ChatCompletionRequest,
    ) -> ExtractedToolCallInformation:
        """Extract tool calls from all ``<｜tool_calls_begin｜>...<｜tool_calls_end｜>`` blocks."""
        if self.TOOL_CALLS_BEGIN not in model_output:
            return ExtractedToolCallInformation(tools_called=False, tool_calls=[], content=model_output)

        tool_calls: list[ToolCall] = []
        content_parts: list[str] = []
        pos = 0
        n = len(model_output)

        while pos < n:
            begin_idx = model_output.find(self.TOOL_CALLS_BEGIN, pos)
            if begin_idx == -1:
                content_parts.append(model_output[pos:])
                break
            body_start = begin_idx + len(self.TOOL_CALLS_BEGIN)
            end_idx = model_output.find(self.TOOL_CALLS_END, body_start)
            if end_idx == -1:
                content_parts.append(model_output[pos:])
                break

            tool_block = model_output[body_start:end_idx]
            block_calls: list[ToolCall] = []
            for part in tool_block.split(self.TOOL_CALL_BEGIN):
                if not part or self.TOOL_CALL_END not in part:
                    continue
                call_content = part.split(self.TOOL_CALL_END, 1)[0]
                if self.TOOL_SEP not in call_content:
                    continue
                type_part, invoke_part = call_content.split(self.TOOL_SEP, 1)
                if type_part.strip() != "function":
                    continue
                function_name, params_dict = self._parse_steptml_invoke(invoke_part)
                if function_name and params_dict is not None:
                    casted_dict = self._cast_arguments(function_name, params_dict, request)
                    try:
                        params_str = json.dumps(casted_dict, ensure_ascii=False)
                    except (TypeError, ValueError, RecursionError):
                        params_str = json.dumps(params_dict, ensure_ascii=False)
                    block_calls.append(ToolCall(function=FunctionCall(name=function_name, arguments=params_str)))

            if block_calls:
                content_parts.append(model_output[pos:begin_idx])
                tool_calls.extend(block_calls)
            else:
                content_parts.append(model_output[pos : end_idx + len(self.TOOL_CALLS_END)])
            pos = end_idx + len(self.TOOL_CALLS_END)

        if tool_calls:
            content = "".join(content_parts).strip()
            return ExtractedToolCallInformation(
                tools_called=True,
                tool_calls=tool_calls,
                content=content if content else None,
            )
        return ExtractedToolCallInformation(tools_called=False, tool_calls=[], content=model_output)
