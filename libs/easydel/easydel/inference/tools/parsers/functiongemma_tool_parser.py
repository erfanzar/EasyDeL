"""FunctionGemma tool parser module.

This module provides the FunctionGemmaToolParser class for parsing tool calls
generated by Google's FunctionGemma model (google/functiongemma-270m-it).

The parser handles a unique format where function calls use escape delimiters
for parameter values within a call: syntax.

Example format parsed:
    <start_function_call>call:func_name{param:<escape>value<escape>}<end_function_call>
"""

