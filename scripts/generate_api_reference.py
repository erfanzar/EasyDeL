"""Generate deterministic API reference artifacts without starting a server."""

from __future__ import annotations

import argparse
import html
import json
from pathlib import Path
from tempfile import TemporaryDirectory

from eyvan._internal.platform import EyvanPlatformConfig
from eyvan.config import EyvanSettings
from eyvan.server.api.app import create_app
from eyvan.server.persistence import InMemoryRepository

METHODS = {"get", "put", "post", "delete", "patch", "head", "options", "trace"}


def documents() -> dict[str, str]:
    # No environment-derived credentials, user profile, daemon, provider or
    # server lifespan. The temporary artifact root keeps construction isolated.
    with TemporaryDirectory(prefix="eyvan-api-reference-") as directory:
        app = create_app(
            settings=EyvanSettings(
                controller_enabled=False,
                artifact_store_uri=directory,
                artifact_token_key="documentation-only-not-a-deployment-credential",
            ),
            repository=InMemoryRepository(),
            platform_config=EyvanPlatformConfig(),
        )
        schema = app.openapi()
    lines = [
        "# Generated API route reference",
        "",
        "Generated by `scripts/generate_api_reference.py`; do not edit manually.",
        "",
        "[OpenAPI schema](openapi.json) contains request/response schemas, parameters,",
        "validation constraints and operation details. See [REST conventions](rest-api.md)",
        "for authentication, authorization, idempotency and streaming behavior.",
        "",
        "This index covers routes included in OpenAPI. Hidden browser callbacks,",
        "static assets and compatibility aliases are not a complete part of that schema.",
        "",
        "| Method | Path | Summary | Responses |",
        "|---|---|---|---|",
    ]
    for path, operations in sorted(schema["paths"].items()):
        for method, operation in sorted(operations.items()):
            if method not in METHODS:
                continue
            summary = html.escape(operation.get("summary", "")).replace("|", r"\|").replace("\n", " ")
            responses = ", ".join(sorted(operation.get("responses", {})))
            lines.append(f"| {method.upper()} | `{path}` | {summary} | {responses} |")
    return {
        "openapi.json": json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        "api-generated.md": "\n".join(lines) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path("docs/reference"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = documents()
    if args.check:
        stale = [
            name
            for name, text in expected.items()
            if not (args.output_dir / name).is_file() or (args.output_dir / name).read_text() != text
        ]
        if stale:
            print("Stale API reference: " + ", ".join(stale))
            return 1
        print("API reference matches the application schema")
        return 0
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, text in expected.items():
        (args.output_dir / name).write_text(text)
    print("Generated API reference in", args.output_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
