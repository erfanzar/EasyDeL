"""Enumerate Eyvan's ``EYVAN_*`` environment-variable surface into one document.

The codebase configures its host daemons through environment variables, and
that surface grew without a single inventory (issue-register item I48). This
script is the inventory's generator, so it cannot rot: run it after any change
and commit the regenerated table next to the policy statement.

    uv run python scripts/enumerate_env_surface.py --check

``--check`` fails when ``docs/env-surface.md`` is stale, which makes the
enumeration CI-enforceable rather than aspirational.
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

_NAME = re.compile(r'"(EYVAN_[A-Z0-9_]+)"')
_HEADER = "<!-- GENERATED by scripts/enumerate_env_surface.py -- do not edit the table by hand. -->"


#: Only the shipped package counts as ground truth -- the same rule
#: ``tests/test_docs_are_grounded.py`` applies when it validates this page.
_PACKAGE = "eyvan"


def _grep_names(root: Path) -> dict[str, set[str]]:
    """Map each variable to the modules that reference it."""

    files = sorted(
        str(path.relative_to(root)) for path in (root / _PACKAGE).rglob("*.py") if "__pycache__" not in path.parts
    )
    where: dict[str, set[str]] = defaultdict(set)
    for relative in files:
        text = (root / relative).read_text(encoding="utf-8")
        for match in _NAME.finditer(text):
            where[match.group(1)].add(relative.removesuffix(".py"))
    return where


def _domain(module_paths: set[str]) -> str:
    """Coarse ownership label: the deepest shared package of the referers."""

    parts = [path.split("/") for path in module_paths]
    shared: list[str] = []
    for level in zip(*parts, strict=False):
        if len(set(level)) == 1 and level[0] != "":
            shared.append(level[0])
        else:
            break
    return "/".join(shared) if shared else sorted(module_paths)[0]


def render(where: dict[str, set[str]]) -> str:
    lines = [
        "# The `EYVAN_*` environment surface",
        "",
        _HEADER,
        "",
        "Eyvan's host daemons (agent, control plane, drivers) are configured",
        "through `EYVAN_*` variables rather than new Python knobs. The project",
        "rule against new `os.environ` knobs governs *library* APIs -- toggles",
        "there belong in constructor or config arguments -- while process-level",
        "daemon configuration is exactly what environments are for. The rule this",
        "document enforces instead is **no unlisted variable**: a name either",
        "appears below or must not exist.",
        "",
        f"{len(where)} variables are currently referenced. Names set on workload",
        "processes as part of the dispatch envelope (attempt ids, batch indices,",
        "candidate digests) sit in the same namespace but are transport, not",
        "configuration; they are listed for completeness because the boundary",
        "is easier to audit when everything is in one table.",
        "",
        "| Variable | Referenced from |",
        "|---|---|",
    ]
    domains: dict[str, list[str]] = defaultdict(list)
    for name, paths in where.items():
        domains[_domain(paths)].append(name)
    for domain in sorted(domains):
        for name in sorted(domains[domain]):
            lines.append(f"| `{name}` | `{domain}` |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated doc is stale.")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    rendered = render(_grep_names(root))
    target = root / "docs" / "env-surface.md"
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != rendered:
            raise SystemExit("docs/env-surface.md is stale; regenerate with scripts/enumerate_env_surface.py")
        print("docs/env-surface.md matches the code")
        return
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {target} ({len(rendered.splitlines())} lines)")


if __name__ == "__main__":
    main()
